/// 픽셀 아이콘 하나. 어두운 그림자를 한 칸 깔아 무대 위에서도 읽히게 한다.
class PixelIconView extends StatelessWidget {
  const PixelIconView(this.icon, {super.key, this.size = 20, this.color = PixelPalette.gold});

  final PixelIcon icon;
  final double size;
  final Color color;

  @override
  Widget build(BuildContext context) => SizedBox(
        width: size,
        height: size,
        child: CustomPaint(painter: _IconPainter(icon, color)),
      );
}

class _IconPainter extends CustomPainter {
  const _IconPainter(this.icon, this.color);

  final PixelIcon icon;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final rows = icon.art.split('\n');
    final cell = size.width / 12;
    final shadow = Paint()
      ..isAntiAlias = false
      ..color = PixelPalette.ink;
    final fill = Paint()
      ..isAntiAlias = false
      ..color = color;

    for (var y = 0; y < rows.length; y++) {
      final row = rows[y];
      for (var x = 0; x < row.length; x++) {
        if (row[x] != '#') continue;
        // 그림자를 먼저 한 칸 아래·오른쪽에.
        canvas.drawRect(Rect.fromLTWH((x + 0.5) * cell, (y + 0.5) * cell, cell, cell), shadow);
      }
    }
    for (var y = 0; y < rows.length; y++) {
      final row = rows[y];
      for (var x = 0; x < row.length; x++) {
        if (row[x] != '#') continue;
        canvas.drawRect(Rect.fromLTWH(x * cell, y * cell, cell, cell), fill);
      }
    }
  }

  @override
  bool shouldRepaint(_IconPainter old) => old.icon != icon || old.color != color;
}
